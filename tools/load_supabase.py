"""Emit SQL that upserts the local jsonl artifacts into the warm_* tables.

Written as `insert ... select from json_to_recordset` so the whole import is a
handful of statements instead of thousands, and so re-running is idempotent.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from match import seniority  # noqa: E402


def load(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def lit(obj):
    """A JSON literal safe to embed in SQL (single quotes doubled)."""
    return "'" + json.dumps(obj, ensure_ascii=False).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--owner", required=True)
    ap.add_argument("--contacts", default="data/contacts.jsonl")
    ap.add_argument("--jobs", default="data/jobs.jsonl")
    ap.add_argument("--matches", default="data/matches.jsonl")
    ap.add_argument("--review", default="data/review_queue.jsonl")
    ap.add_argument("--out", default="data/load.sql")
    ap.add_argument("--self-source", default="nate",
                    help="source name that is your own network")
    args = ap.parse_args()

    contacts = load(args.contacts)
    jobs = load(args.jobs)
    matches = load(args.matches)
    review = load(args.review)
    owner = args.owner

    sources = sorted({c["source"] for c in contacts})
    src_rows = [{"name": s, "trust": 1.5 if s == args.self_source else 1.0}
                for s in sources]

    people, affs = {}, {}
    for c in contacts:
        key = (c["source"], c["person_norm"])
        prior = people.get(key)
        if prior is None or (c.get("linkedin_url") and not prior.get("linkedin_url")):
            people[key] = {
                "source": c["source"], "full_name": c["full_name"],
                "person_norm": c["person_norm"],
                "linkedin_url": c.get("linkedin_url") or None,
                "email": c.get("email") or None,
            }
        akey = (c["source"], c["person_norm"], c["company_norm"])
        cand = {
            "source": c["source"], "person_norm": c["person_norm"],
            "company_raw": c["company_raw"], "company_norm": c["company_norm"],
            "role": c.get("role") or None, "seniority": seniority(c.get("role")),
        }
        if akey not in affs or cand["seniority"] > affs[akey]["seniority"]:
            affs[akey] = cand

    job_rows = [{
        "linkedin_job_id": j["linkedin_job_id"], "title": j["title"],
        "company_raw": j["company_raw"], "company_norm": j["company_norm"],
        "company_slug": j["company_slug"], "location": j["location"],
        "url": j["url"], "posted_on": j["posted_on"],
        "query_label": j["query_label"],
    } for j in jobs]

    jc_rows = [{
        "linkedin_job_id": m["linkedin_job_id"], "source": m["source"],
        "person_norm": m["person_norm"],
        "strength": m["strength"], "confidence": m["confidence"],
        "contacts_at_company": m["contacts_at_company"],
    } for m in matches]

    rv_rows = [{
        "job_company": r["job_company"], "job_company_norm": r["job_company_norm"],
        "candidate_norm": r["candidate_norm"],
        "candidate_example": r.get("candidate_example"),
        "contact_count": r["contact_count"], "score": r["score"],
    } for r in review]

    sql = f"""
-- Generated by tools/load_supabase.py. Idempotent: safe to re-run.
begin;

insert into warm_sources (owner_id, name, trust)
select '{owner}'::uuid, x.name, x.trust
from json_to_recordset({lit(src_rows)}::json) as x(name text, trust numeric)
on conflict (owner_id, name) do update set trust = excluded.trust;

insert into warm_contacts (owner_id, source_id, full_name, person_norm, linkedin_url, email)
select '{owner}'::uuid, s.id, x.full_name, x.person_norm, x.linkedin_url, x.email
from json_to_recordset({lit(list(people.values()))}::json)
     as x(source text, full_name text, person_norm text, linkedin_url text, email text)
join warm_sources s on s.owner_id = '{owner}'::uuid and s.name = x.source
on conflict (owner_id, source_id, person_norm) do update
  set full_name = excluded.full_name,
      linkedin_url = coalesce(excluded.linkedin_url, warm_contacts.linkedin_url);

insert into warm_affiliations (owner_id, contact_id, company_raw, company_norm, role, seniority)
select '{owner}'::uuid, c.id, x.company_raw, x.company_norm, x.role, x.seniority
from json_to_recordset({lit(list(affs.values()))}::json)
     as x(source text, person_norm text, company_raw text, company_norm text,
          role text, seniority int)
join warm_sources s  on s.owner_id = '{owner}'::uuid and s.name = x.source
join warm_contacts c on c.owner_id = '{owner}'::uuid and c.source_id = s.id
                    and c.person_norm = x.person_norm
on conflict (owner_id, contact_id, company_norm) do update
  set role = excluded.role, seniority = excluded.seniority;

insert into warm_jobs (owner_id, linkedin_job_id, title, company_raw, company_norm,
                       company_slug, location, url, posted_on, query_label)
select '{owner}'::uuid, x.linkedin_job_id, x.title, x.company_raw, x.company_norm,
       x.company_slug, x.location, x.url, x.posted_on, x.query_label
from json_to_recordset({lit(job_rows)}::json)
     as x(linkedin_job_id text, title text, company_raw text, company_norm text,
          company_slug text, location text, url text, posted_on date, query_label text)
-- Never clobber triage state on a re-scrape.
on conflict (owner_id, linkedin_job_id) do nothing;

insert into warm_job_contacts (owner_id, job_id, contact_id, strength, confidence, contacts_at_company)
select '{owner}'::uuid, j.id, c.id, x.strength, x.confidence, x.contacts_at_company
from json_to_recordset({lit(jc_rows)}::json)
     as x(linkedin_job_id text, source text, person_norm text, strength numeric,
          confidence text, contacts_at_company int)
join warm_jobs j     on j.owner_id = '{owner}'::uuid and j.linkedin_job_id = x.linkedin_job_id
join warm_sources s  on s.owner_id = '{owner}'::uuid and s.name = x.source
join warm_contacts c on c.owner_id = '{owner}'::uuid and c.source_id = s.id
                    and c.person_norm = x.person_norm
on conflict (job_id, contact_id) do update set strength = excluded.strength;

insert into warm_review_queue (owner_id, job_company, job_company_norm, candidate_norm,
                              candidate_example, contact_count, score)
select '{owner}'::uuid, x.job_company, x.job_company_norm, x.candidate_norm,
       x.candidate_example, x.contact_count, x.score
from json_to_recordset({lit(rv_rows)}::json)
     as x(job_company text, job_company_norm text, candidate_norm text,
          candidate_example text, contact_count int, score numeric)
on conflict (owner_id, job_company_norm, candidate_norm) do nothing;

commit;
"""
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(sql)
    print(f"{len(src_rows)} sources / {len(people)} contacts / {len(affs)} affiliations / "
          f"{len(job_rows)} jobs / {len(jc_rows)} job-contacts / {len(rv_rows)} review "
          f"-> {args.out} ({os.path.getsize(args.out)//1024} KB)")


if __name__ == "__main__":
    main()
